def test_control_routes_are_frozen(app) -> None:
    paths = {getattr(route, "path", "") for route in app.routes}
    paths.discard("")
    missing = CONTROL_ROUTES - paths
    assert not missing, f"控制面路由缺失：{sorted(missing)}"


def test_event_contract_is_frozen() -> None:
    types = {
        cls.model_fields["type"].default for cls in get_args(EventType)
    }
    assert types == REQUIRED_EVENT_TYPES

    approval_fields = set(ApprovalRequested.model_fields)
    assert {
        "request_id",
        "tool",
        "command",
        "level",
        "reason",
    } <= approval_fields


def test_sse_framing_and_suspension_are_frozen() -> None:
    event = RunStarted(thread_id="t1")
    assert _sse(event).startswith("data: ")
    frame = _sse_with_id(event, 3)
    assert frame.startswith("id: 3\ndata: ")
    assert '"type":"run_started"' in frame

    assert _is_suspended(ApprovalRequested(request_id="a"))
    assert _is_suspended(SteeringApplied(action="pause"))
    assert not _is_suspended(SteeringApplied(action="resume"))
    assert not _is_suspended(RunFinished(answer="done"))
    assert _STREAM_BUFFER_MAX_CHARS == 8 * 1024 * 1024


def test_frontend_is_built_from_ts_source() -> None:
    source = Path("src/coding_agent/web/frontend/src/app.ts")
    built = Path("src/coding_agent/web/static/app.js")
    assert source.is_file()
    text = built.read_text(encoding="utf-8")
    assert text.startswith("// Generated by esbuild")
    assert "registerAgentApp" in text


