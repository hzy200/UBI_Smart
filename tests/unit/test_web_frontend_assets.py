"""Phase E：前端静态资产、CSP 与构建产物契约。"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STATIC = ROOT / "src" / "coding_agent" / "web" / "static"


def _read(name: str) -> str:
    return (STATIC / name).read_text(encoding="utf-8")


def test_index_references_only_local_existing_assets() -> None:
    html = _read("index.html")
    refs = re.findall(r'(?:src|href)="([^"]+)"', html)
    assert refs
    for ref in refs:
        assert not ref.startswith(("http://", "https://", "//")), ref
        if ref.startswith("/static/"):
            target = STATIC / ref[len("/static/") :]
            assert target.is_file(), ref
    assert "<script>" not in html  # 不允许内联脚本破坏 CSP


def test_bundle_is_generated_and_contains_phase_e_hooks() -> None:
    bundle = _read("app.js")
    assert "Generated by esbuild" in bundle
    for token in (
        "consumeSse",
        "reasoningBlocks",
        "scheduleReconnect",
        "decorateTranscript",
        "family-",
        "theme-",
    ):
        assert token in bundle, token


def test_vendor_assets_are_documented() -> None:
    readme = (STATIC / "vendor" / "README.md").read_text(encoding="utf-8")
    assert "highlight.js 11.11.1" in readme
    assert (STATIC / "vendor" / "highlight.min.js").stat().st_size > 100_000


def test_theme_and_accessibility_markers() -> None:
    css = _read("style.css")
    html = _read("index.html")
    assert ".theme-auto" in css
    assert "prefers-color-scheme" in css
    assert "prefers-reduced-motion" in css
    assert "content-visibility: auto" in css
    assert 'aria-live="polite"' in html
    assert 'role="dialog"' in html
    assert 'aria-label="对话记录"' in html
