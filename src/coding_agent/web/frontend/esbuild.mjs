import * as esbuild from "esbuild";
import { watch as watchFs } from "node:fs";
import { buildUi } from "./build-ui.mjs";

const watch = process.argv.includes("--watch");

const shared = {
  bundle: true,
  format: "iife",
  target: "es2020",
  sourcemap: false,
  legalComments: "none",
};

const appOptions = {
  ...shared,
  entryPoints: ["src/main.ts"],
  outfile: "../static/app.js",
  banner: {
    js: "// Generated by esbuild from frontend/src; do not edit static/app.js directly.",
  },
};

const adminOptions = {
  ...shared,
  entryPoints: ["src/admin/main.tsx"],
  outfile: "../static/admin/app.js",
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  minify: true,
  banner: {
    js: "// Generated by esbuild from frontend/src/admin; do not edit static/admin/app.js directly.",
  },
};

const adminCssOptions = {
  entryPoints: ["src/admin/admin.css"],
  outfile: "../static/admin/app.css",
  bundle: true,
  minify: true,
  legalComments: "none",
};

async function buildUiQuiet() {
  const outputs = await buildUi();
  for (const file of outputs) console.log(`built ${file}`);
}

if (watch) {
  const contexts = await Promise.all(
    [appOptions, adminOptions, adminCssOptions].map((options) =>
      esbuild.context(options),
    ),
  );
  await Promise.all(contexts.map((ctx) => ctx.watch()));
  await buildUiQuiet();
  let timer = null;
  const rebuild = () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      buildUiQuiet().catch((err) => console.error(err));
    }, 80);
  };
  for (const [dir, name] of [
    ["src/templates", "templates"],
    ["src/styles", "styles"],
    ["src/admin", "admin"],
  ]) {
    try {
      watchFs(dir, { recursive: true }, rebuild);
    } catch (err) {
      // 目录尚未创建或平台不支持递归监听时，仍可用手动构建。
      console.warn(`watch ${name} unavailable: ${err.message}`);
    }
  }
  console.log("watching frontend...");
} else {
  await Promise.all(
    [appOptions, adminOptions, adminCssOptions].map((options) =>
      esbuild.build(options),
    ),
  );
  console.log("built ../static/app.js");
  console.log("built ../static/admin/app.js");
  console.log("built ../static/admin/app.css");
  await buildUiQuiet();
}
