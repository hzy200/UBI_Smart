"""用 esbuild 生成 static/app.js（Phase B5）。

不要求本地 node_modules：直接调用 `npx --yes esbuild`，适合 CI/首次构建。
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FRONTEND = ROOT / "src" / "coding_agent" / "web" / "frontend"
OUT = ROOT / "src" / "coding_agent" / "web" / "static" / "app.js"


def main() -> int:
    if shutil.which("npx") is None and shutil.which("npx.cmd") is None:
        print("未找到 npx；请安装 Node.js 18+")
        return 2
    npx = [
        "npx",
        "--yes",
        "esbuild@0.28.2",
        "src/main.ts",
        "--bundle",
        "--format=iife",
        "--target=es2020",
        "--legal-comments=none",
        "--banner:js=// Generated by esbuild from frontend/src; "
        "do not edit static/app.js directly.",
        f"--outfile={OUT}",
    ]
    command = (
        [os.environ.get("COMSPEC", "cmd.exe"), "/c", *npx]
        if os.name == "nt"
        else npx
    )
    print(" ".join(command))
    result = subprocess.run(command, cwd=FRONTEND, check=False)
    return int(result.returncode)


if __name__ == "__main__":
    sys.exit(main())
